-- LA ROSA — Schéma Supabase
-- À exécuter dans Supabase > SQL Editor.
create extension if not exists pgcrypto;

create table if not exists public.menu_sections (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  icon text not null default '🍽️',
  sort_order integer not null default 0
);
create table if not exists public.menu_items (
  id bigint generated by default as identity primary key,
  section_id bigint not null references public.menu_sections(id) on delete cascade,
  name text not null,
  description text not null default '',
  price numeric(10,2) not null check (price >= 0),
  sort_order integer not null default 0
);
create table if not exists public.hookah_prices (
  id bigint generated by default as identity primary key,
  flavour text not null,
  classic_price numeric(10,2) not null default 0 check (classic_price >= 0),
  kaloud_price numeric(10,2) not null default 0 check (kaloud_price >= 0),
  quasar_price numeric(10,2) not null default 0 check (quasar_price >= 0),
  sort_order integer not null default 0
);
create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.menu_sections enable row level security;
alter table public.menu_items enable row level security;
alter table public.hookah_prices enable row level security;
alter table public.admin_users enable row level security;

-- Public clients can only READ the menu.
create policy "Public can read menu sections" on public.menu_sections
for select to anon, authenticated using (true);
create policy "Public can read menu items" on public.menu_items
for select to anon, authenticated using (true);
create policy "Public can read hookah prices" on public.hookah_prices
for select to anon, authenticated using (true);

-- Admins can read their own membership row; writes are allowed only if a matching
-- admin_users row exists. The admin_users table itself has no public write policies.
create policy "Admins can read own membership" on public.admin_users
for select to authenticated using (user_id = auth.uid());

create policy "Admins insert sections" on public.menu_sections
for insert to authenticated with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "Admins update sections" on public.menu_sections
for update to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid())) with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "Admins delete sections" on public.menu_sections
for delete to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

create policy "Admins insert items" on public.menu_items
for insert to authenticated with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "Admins update items" on public.menu_items
for update to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid())) with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "Admins delete items" on public.menu_items
for delete to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

create policy "Admins insert hookah" on public.hookah_prices
for insert to authenticated with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "Admins update hookah" on public.hookah_prices
for update to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid())) with check (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "Admins delete hookah" on public.hookah_prices
for delete to authenticated using (exists(select 1 from public.admin_users a where a.user_id = auth.uid()));

